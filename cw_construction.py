def tseq_from_turyn(l):
    """T-sequences of length 4l-1 from Turyn sequences (Seb2017 Thm 7.7)."""
    tx, tu, ty, tv = turyn_db(l)
    L = 4 * l - 1
    x1 = [1] + [0] * (L - 1)
    def interleave(s1, s2):
        return [s1[i//2] if i%2==0 else s2[(i-1)//2] for i in range(len(s1)+len(s2))]
    x2 = [0] + interleave(tx, ty) + [0] * (2*l - 1)
    x3 = [0] * (2*l) + interleave(tu, [0] * (l - 1))
    x4 = [0] * (2*l) + interleave([0] * l, tv)
    return [x1, x2, x3, x4]


def tseq_from_base(l):
    """T-sequences of length 2(l+len(C))-? from base=T_sequences_construction_from_base_sequences.
    Actually from Theorem: Turyn → base sequences, from base → T-seq.
    Shortcut: the SageMath function T_sequences_construction_from_base_sequences
    takes Turyn sequences and produces T-sequences of length 2n+p where
    n = len(turyn[2]) and p = len(turyn[0]) - len(turyn[2]) = 1.
    So T_length = 2*n + p = 2*len(C) + (len(A)-len(C)).
    For Turyn(l): A,B have length l-1, C,D have length l-2.
    So p = (l-1) - (l-2) = 1, n = l-2.
    T_length = 2*(l-2) + 1 = 2l - 3.
    But the SageMath function name is 'T_sequences_construction_from_base_sequences' which
    calls base_sequences_smallcases first. Let me simplify.
    """
    A, B, C, D = turyn_db(l)
    n = len(C)      # = l-2 for l≥3, =1 for l=2
    p = len(A) - n  # = 1
    T_len = 2 * n + p
    x1 = [((a + b) // 2) for a,b in zip(A,B)] + [0]*n
    x2 = [((a - b) // 2) for a,b in zip(A,B)] + [0]*n
    x3 = [0]*(n+p) + [((c + d) // 2) for c,d in zip(C,D)]
    x4 = [0]*(n+p) + [((c - d) // 2) for c,d in zip(C,D)]
    return [x1, x2, x3, x4]


