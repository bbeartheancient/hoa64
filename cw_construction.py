def tsequences_available(t):
    """Check if T-sequences of length t are available."""
    if t in tseq_direct_db(0) or t in (47, 65, 93):
        return True
    if (t + 1) % 2 == 0:
        l = (t + 1) // 2
        if turyn_db(l) is not None:
            return True
    if (t + 1) % 4 == 0:
        l = (t + 1) // 4
        if turyn_db(l) is not None:
            return True
    return False


def tsequences_get(t):
    """Get T-sequences of length t (list of 4 lists)."""
    d = tseq_direct_db(t)
    if d is not None:
        return d
    if (t + 1) % 2 == 0:
        l = (t + 1) // 2
        if turyn_db(l) is not None:
            return tseq_from_base(l)
    if (t + 1) % 4 == 0:
        l = (t + 1) // 4
        if turyn_db(l) is not None:
            return tseq_from_turyn(l)
    return None


