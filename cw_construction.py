"""Cooper-Wallis Hadamard construction ported from SageMath.

Turyn sequences → T-sequences → CW H(4t) via Williamson block assembly.
"""

import numpy as np


def seq_to_circulant(s):
    k = len(s)
    M = np.empty((k, k), dtype=np.int64)
    for i in range(k):
        M[i] = np.roll(s, i)
    return M


def gs_array(A, B, C, D):
    k = A.shape[0]
    R = np.eye(k, dtype=np.int64)[::-1]
    return np.block([
        [    A,   B@R,   C@R,   D@R],
        [ -B@R,     A, -D.T@R,  C.T@R],
        [ -C@R,  D.T@R,     A, -B.T@R],
        [ -D@R, -C.T@R,  B.T@R,     A],
    ]).astype(np.int8)


