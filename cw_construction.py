def cw_build(order):
    """Build CW Hadamard of order n = 4*t.
    t = T_seq_len × will_size, where both must be available."""
    if order % 4 != 0:
        return None
    t = order // 4
    for ts_len in {47, 65, 93} | {3,5,7,9,11,13,15,19,23,25,27,29,31,51,59}:
        if t % ts_len != 0:
            continue
        ws = t // ts_len
        if ws not in WILL_DB:
            continue
        x1l,x2l,x3l,x4l = tsequences_get(ts_len)
        x1=np.array(x1l,dtype=np.int64);x2=np.array(x2l,dtype=np.int64)
        x3=np.array(x3l,dtype=np.int64);x4=np.array(x4l,dtype=np.int64)
        aw,bw,cw,dw=[will_to_seq(s) for s in WILL_DB[ws]]
        A=seq_to_circulant(aw);B=seq_to_circulant(bw)
        C=seq_to_circulant(cw);D=seq_to_circulant(dw)
        X1=seq_to_circulant(x1);X2=seq_to_circulant(x2)
        X3=seq_to_circulant(x3);X4=seq_to_circulant(x4)
        e1=gs_array(X1,X2,X3,X4)
        e2=gs_array(X2,-X1,X4,-X3)
        e3=gs_array(X3,-X4,-X1,X2)
        e4=gs_array(X4,X3,-X2,-X1)
        H=np.kron(e1,A)+np.kron(e2,B)+np.kron(e3,C)+np.kron(e4,D)
        return H.astype(np.int8)
    return None
